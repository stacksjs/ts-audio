"""Writes src/celt-tables.ts from c_arrays.py's JSON of libopus's CELT sources."""
import json, sys
d = json.load(open(sys.argv[1]))
def arr(vals, width=16, kind='int'):
    vals = [repr(float(v)) for v in vals] if kind == 'float' else [str(v) for v in vals]
    rows = [', '.join(vals[i:i + width]) for i in range(0, len(vals), width)]
    return '[\n  ' + ',\n  '.join(rows) + ',\n]'
spec = [
    ('EBANDS', 'eband5ms', 'Int16Array', 'int', 'Band edges of the 48 kHz mode, in 2.5 ms (120-line) units: 21 bands.'),
    ('BAND_ALLOCATION', 'band_allocation', 'Uint8Array', 'int', '11 allocation vectors of 21 bands, in 1/32 bit per sample.'),
    ('LOG_N', 'logN400', 'Int16Array', 'int', 'log2 of each band\'s width, in 1/8 bits.'),
    ('CACHE_INDEX', 'cache_index50', 'Int16Array', 'int', 'Where each band and frame size\'s pulse cache starts in CACHE_BITS.'),
    ('CACHE_BITS', 'cache_bits50', 'Uint8Array', 'int', 'Bits each number of pulses costs, by band and frame size.'),
    ('CACHE_CAPS', 'cache_caps50', 'Uint8Array', 'int', 'The most bits a band can use, by frame size and channel count.'),
    ('PVQ_U_DATA', 'CELT_PVQ_U_DATA', 'Uint32Array', 'int', 'U(N, K), the PVQ codebook sizes, row by row.'),
    ('E_PROB_MODEL', 'e_prob_model', 'Uint8Array', 'int', 'Laplace parameters of the coarse energy, by frame size, intra flag and band.'),
    ('E_MEANS', 'eMeans', 'Float32Array', 'float', 'Mean band energy, in log2 units.'),
    ('WINDOW', 'window120', 'Float32Array', 'float', 'The 120-sample overlap window.'),
    ('LOG2_FRAC_TABLE', 'LOG2_FRAC_TABLE', 'Uint8Array', 'int', 'log2 of 1 to 24, in 1/8 bits, for the intensity reservation.'),
    ('MDCT_TWIDDLES', 'mdct_twiddles960', 'Float32Array', 'float', 'cos(2π(i + 1/8)/N) for N = 1920, 960, 480 and 240, one after another.'),
]
out = ['''/**
 * CELT tables for the 48 kHz, 20 ms mode Opus uses (RFC 6716).
 *
 * Extracted from libopus 1.5.2, Copyright 2001-2023 Xiph.Org, Skype Limited,
 * Octasic, Jean-Marc Valin, Timothy B. Terriberry, CSIRO, Gregory Maxwell,
 * Mark Borgerding, Erik de Castro Lopo, Mozilla, Amazon; BSD 3-clause
 * licence, in THIRD_PARTY_NOTICES.md.
 *
 * Generated by scripts/opus-tables: do not edit by hand.
 */
''']
for name, key, typ, kind, doc in spec:
    out.append(f'/** {doc} */\nexport const {name}: {typ} = {typ}.from({arr(d[key], 16, kind)})\n')
out.append('''/** Row offsets of PVQ_U_DATA: U(n, k) for n, k with min(n, k) = row. */
export const PVQ_U_ROWS: readonly number[] = [0, 176, 351, 525, 698, 870, 1041, 1131, 1178, 1207, 1226, 1240, 1248, 1254, 1257]
''')
open(sys.argv[2], 'w').write('\n'.join(out))
